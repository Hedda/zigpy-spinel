use zzigbee_frames::*;

#[test]
fn test_decryption() {
    let bytes = [
        0x48, 0x06, 0x5c, 0xce, 0x00, 0x00, 0x1d, 0x54, 0x01, 0x00, 0x50, 0x2f, 0x28,
        0x45, 0x87, 0x13, 0x00, 0x2f, 0xd5, 0x70, 0xfe, 0xff, 0x08, 0xac, 0x70, 0x00,
        0xcd, 0xbc, 0x78, 0xd5, 0x0d, 0xd1, 0x68, 0x27, 0x08, 0x61, 0x53, 0x2d, 0xba,
        0x10, 0x24, 0x88, 0xc4,
    ];

    let frame = NwkFrame::from_bytes(&bytes).unwrap();
    assert_eq!(frame.encrypted, true);

    println!("Frame: {:#?}", frame);

    let key = Key{0: [0xc8, 0x0d, 0x48, 0xca, 0x50, 0x9a, 0x45, 0x8b, 0xfd, 0xdc, 0x30, 0x6f, 0x4b, 0x16, 0x88, 0xdf]};

    let decrypted_frame = frame.decrypt(&key).expect("Failed to decrypt frame");
    assert_eq!(decrypted_frame.encrypted, false);
    assert_eq!(decrypted_frame.payload, [0x40, 0x01, 0x02, 0x07, 0x04, 0x01, 0x01, 0xd3, 0x18, 0x40, 0x0b, 0x0a, 0x00]);
}